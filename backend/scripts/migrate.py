"""Database schema helper: drift check and optional Alembic bootstrap.

BioTrace uses ``Base.metadata.create_all()`` for a beginner-friendly first run. That
is fine for a fresh clone, but it cannot alter existing tables. This script helps you
move to real migrations without hand-editing anything.

Usage (from the project root):

    python -m backend.scripts.migrate --check
    python -m backend.scripts.migrate --bootstrap

``--check`` compares the tables in ``DATABASE_URL`` against the SQLAlchemy models and
reports anything missing or unexpected. It never modifies data.

``--bootstrap`` writes ``alembic.ini`` and ``migrations/env.py`` wired to
``backend.app.database.Base``. It refuses to overwrite existing files, and requires
the optional ``alembic`` package.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

ALEMBIC_INI = """# Alembic configuration for BioTrace.
# Generated by backend/scripts/migrate.py --bootstrap

[alembic]
script_location = migrations
prepend_sys_path = .
version_path_separator = os

[loggers]
keys = root,sqlalchemy,alembic

[handlers]
keys = console

[formatters]
keys = generic

[logger_root]
level = WARN
handlers = console
qualname =

[logger_sqlalchemy]
level = WARN
handlers =
qualname = sqlalchemy.engine

[logger_alembic]
level = INFO
handlers =
qualname = alembic

[handler_console]
class = StreamHandler
args = (sys.stderr,)
level = NOTSET
formatter = generic

[formatter_generic]
format = %(levelname)-5.5s [%(name)s] %(message)s
datefmt = %H:%M:%S
"""

ALEMBIC_ENV = '''"""Alembic environment wired to the BioTrace models.

Generated by backend/scripts/migrate.py --bootstrap.
"""

from __future__ import annotations

import sys
from logging.config import fileConfig
from pathlib import Path

from alembic import context
from sqlalchemy import engine_from_config, pool

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from backend.app import models  # noqa: F401  (registers mappers)
from backend.app.config import settings
from backend.app.database import Base

config = context.config
config.set_main_option("sqlalchemy.url", settings.database_url)

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata


def run_migrations_offline() -> None:
    context.configure(
        url=settings.database_url,
        target_metadata=target_metadata,
        literal_binds=True,
        compare_type=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    with connectable.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            compare_type=True,
            render_as_batch=True,  # SQLite needs batch mode for ALTERs
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
'''


def _parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Check BioTrace schema drift or bootstrap Alembic.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check", action="store_true", help="Report schema drift.")
    group.add_argument("--bootstrap", action="store_true", help="Write Alembic config files.")
    return parser.parse_args(argv)


def check() -> int:
    from sqlalchemy import inspect

    from backend.app import models  # noqa: F401
    from backend.app.config import settings
    from backend.app.database import Base, engine

    print(f"Database: {settings.database_url}")
    existing = set(inspect(engine).get_table_names())
    expected = set(Base.metadata.tables)

    missing = sorted(expected - existing)
    unexpected = sorted(name for name in existing - expected if name != "alembic_version")

    if not missing and not unexpected:
        print(f"OK: all {len(expected)} model tables exist and no unexpected tables were found.")
        return 0

    if missing:
        print(f"Missing tables ({len(missing)}): {', '.join(missing)}")
        print("  Fix: start the app once (init_db creates tables) or use migrations.")
    if unexpected:
        print(f"Unexpected tables ({len(unexpected)}): {', '.join(unexpected)}")
        print("  These are not in the models and may be leftovers from older versions.")
    return 1


def bootstrap() -> int:
    try:
        import alembic  # noqa: F401
    except ImportError:
        print(
            "Alembic is not installed. Run:\n  pip install alembic\n",
            file=sys.stderr,
        )
        return 2

    ini_path = PROJECT_ROOT / "alembic.ini"
    migrations_dir = PROJECT_ROOT / "migrations"
    env_path = migrations_dir / "env.py"
    versions_dir = migrations_dir / "versions"

    for path in (ini_path, env_path):
        if path.exists():
            print(f"Refusing to overwrite existing {path}", file=sys.stderr)
            return 2

    versions_dir.mkdir(parents=True, exist_ok=True)
    ini_path.write_text(ALEMBIC_INI, encoding="utf-8")
    env_path.write_text(ALEMBIC_ENV, encoding="utf-8")
    (migrations_dir / "script.py.mako").write_text(
        _SCRIPT_MAKO, encoding="utf-8"
    )

    print(f"Wrote {ini_path}")
    print(f"Wrote {env_path}")
    print(f"Wrote {migrations_dir / 'script.py.mako'}")
    print(
        "\nNext steps:\n"
        "  1. Restrict-host the generated files if needed (alembic.ini has no secrets).\n"
        "  2. Point DATABASE_URL at your database.\n"
        "  3. Create the baseline revision:\n"
        "       alembic revision --autogenerate -m 'baseline'\n"
        "  4. Review the generated file in migrations/versions/, then apply it:\n"
        "       alembic upgrade head\n"
        "  5. From now on, use `alembic revision --autogenerate` for every model change\n"
        "     instead of relying on init_db().\n"
    )
    return 0


_SCRIPT_MAKO = '''"""${message}

Revision ID: ${up_revision}
Revises: ${down_revision | comma,n}
Create Date: ${create_date}
"""
from __future__ import annotations

from alembic import op
import sqlalchemy as sa
${imports if imports else ""}

revision = ${repr(up_revision)}
down_revision = ${repr(down_revision)}
branch_labels = ${repr(branch_labels)}
depends_on = ${repr(depends_on)}


def upgrade() -> None:
    ${upgrades if upgrades else "pass"}


def downgrade() -> None:
    ${downgrades if downgrades else "pass"}
'''


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv)
    return check() if args.check else bootstrap()


if __name__ == "__main__":
    raise SystemExit(main())
